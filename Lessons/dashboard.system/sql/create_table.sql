-- Safe teardown blocks to allow clean script re-runs without naming collisions
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE SUBJECTS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE LOGIN_USERS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE STUDENTS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL; END;
/

-- 1. Create the Master Academic Tracking Table
CREATE TABLE STUDENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255) NOT NULL,
    MARKS NUMBER CHECK (MARKS BETWEEN 0 AND 100),
    ATTENDANCE NUMBER CHECK (ATTENDANCE BETWEEN 0 AND 100),
    GRADE VARCHAR2(20),
    RESULT VARCHAR2(100)
);

-- 2. Create the User Security Credential Table
CREATE TABLE LOGIN_USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) UNIQUE NOT NULL,
    PASSWORD VARCHAR2(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Create the Relational Subjects Table with Cascading Deletions
CREATE TABLE SUBJECTS (
    SUBJECT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    SUBJECT_NAME VARCHAR2(100) NOT NULL,
    MARKS_OBTAINED NUMBER CHECK (MARKS_OBTAINED BETWEEN 0 AND 100),
    CONSTRAINT fk_student 
        FOREIGN KEY (STUDENT_ID) 
        REFERENCES STUDENTS(ID) 
        ON DELETE CASCADE
);